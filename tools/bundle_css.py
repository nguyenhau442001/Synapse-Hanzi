#!/usr/bin/env python3
"""
tools/bundle_css.py

Concatenates modular component CSS files from assets/css/ into assets/flashcards.css.
Eliminates @import network cascades while preserving individual source files for development & unit testing.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Ordered CSS manifest to maintain accurate cascade rules (variables -> layout -> components)
BUNDLE_FILES = [
    "assets/css/base.css",
    "assets/css/level-picker.css",
    "assets/css/flashcard.css",
    "assets/css/workstation.css",
    "assets/css/sidebar-lab.css",
    "assets/css/home-widgets.css",
    "assets/css/dashboard-enhancements.css",
    "assets/css/quick-access-drawer.css",
    "assets/css/reading-analysis.css",
    "assets/css/graded-reading.css",
    "assets/css/fast-review-picker.css",
    "assets/css/fast-review.css",
    "assets/css/sentence-game.css",
    "assets/css/radicals.css",
    "assets/css/streak-history.css",
    "assets/css/vocabulary-overview.css",
    "assets/css/celebration.css",
    "assets/css/study-help-modal.css",
    "assets/css/feedback.css",
    "assets/css/footer.css",
]

OUTPUT_FILE = ROOT / "assets" / "flashcards.css"


def build_bundle():
    parts = [
        "/* ==========================================================================\n"
        "   Synapse Hanzi · Unified Stylesheet Bundle\n"
        "   Generated by tools/bundle_css.py — DO NOT edit directly;\n"
        "   edit modular component stylesheets in assets/css/ instead.\n"
        "   ========================================================================== */\n"
    ]
    for rel in BUNDLE_FILES:
        path = ROOT / rel
        if not path.exists():
            raise FileNotFoundError(f"Missing CSS source file: {rel}")
        content = path.read_text(encoding="utf-8").strip()
        parts.append(f"\n/* --- {rel} --- */\n{content}\n")

    OUTPUT_FILE.write_text("".join(parts), encoding="utf-8")
    print(f"Bundled {len(BUNDLE_FILES)} CSS files -> {OUTPUT_FILE} ({OUTPUT_FILE.stat().st_size:,} bytes)")


if __name__ == "__main__":
    build_bundle()
