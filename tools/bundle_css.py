#!/usr/bin/env python3
"""
tools/bundle_css.py

Concatenates modular component CSS files from assets/css/ into assets/flashcards.css.
Eliminates @import network cascades while preserving individual source files for development & unit testing.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Ordered CSS manifest to maintain accurate cascade rules (variables -> layout -> components)
BUNDLE_FILES = [
    "assets/css/base.css",
    "assets/css/level-picker.css",
    "assets/css/flashcard.css",
    "assets/css/workstation.css",
    "assets/css/sidebar-lab.css",
    "assets/css/home-widgets.css",
    "assets/css/dashboard-enhancements.css",
    "assets/css/quick-access-drawer.css",
    "assets/css/reading-analysis.css",
    "assets/css/graded-reading.css",
    "assets/css/fast-review-picker.css",
    "assets/css/fast-review.css",
    "assets/css/sentence-game.css",
    "assets/css/radicals.css",
    "assets/css/streak-history.css",
    "assets/css/vocabulary-overview.css",
    "assets/css/celebration.css",
    "assets/css/study-help-modal.css",
    "assets/css/feedback.css",
    "assets/css/footer.css",
]

OUTPUT_FILE = ROOT / "assets" / "flashcards.css"


def minify_css(css: str) -> str:
    """Safely minifies CSS by removing comments, collapsing whitespace,

    stripping unnecessary semicolons and spaces, while preserving calc() operands.
    """
    # 1. Strip comments
    css = re.sub(r"/\*[\s\S]*?\*/", "", css)
    # 2. Normalize whitespace (tabs, newlines, multiple spaces)
    css = re.sub(r"\s+", " ", css)
    # 3. Strip spaces around structural delimiters: { } ; ,
    css = re.sub(r"\s*([\{\};,])\s*", r"\1", css)
    # 4. Strip space after property colons
    css = re.sub(r":\s+", ":", css)
    # 5. Remove trailing semicolon before closing brace
    css = re.sub(r";}", "}", css)
    # 6. Remove empty rulesets
    css = re.sub(r"[^{};]+{}", "", css)
    return css.strip()


def build_bundle(minify: bool = True):
    banner = (
        "/* Synapse Hanzi · Unified Stylesheet Bundle\n"
        "   Generated by tools/bundle_css.py — DO NOT edit directly;\n"
        "   edit modular component stylesheets in assets/css/ instead. */\n"
    )
    raw_parts = []
    for rel in BUNDLE_FILES:
        path = ROOT / rel
        if not path.exists():
            raise FileNotFoundError(f"Missing CSS source file: {rel}")
        content = path.read_text(encoding="utf-8").strip()
        raw_parts.append(content)

    combined = "\n".join(raw_parts)
    if minify:
        bundled = banner + minify_css(combined)
    else:
        bundled = banner + "\n" + combined

    OUTPUT_FILE.write_text(bundled, encoding="utf-8")
    reduction = (1 - len(bundled) / len(combined)) * 100 if minify else 0
    print(
        f"Bundled {len(BUNDLE_FILES)} CSS files -> {OUTPUT_FILE} "
        f"({OUTPUT_FILE.stat().st_size:,} bytes, -{reduction:.1f}% minified)"
    )


if __name__ == "__main__":
    do_minify = "--no-minify" not in sys.argv
    build_bundle(minify=do_minify)
